//! 统一的缓动函数库。
//!
//! 各个动画的缓动曲线集中在这里 —— 原来散在画布代码里的
//! `1.0 - (1.0 - t) * (1.0 - t)` 之类，现在都从这儿取。改一处，用它的动画都跟着变。

/// 二次方缓出：快速启动、平滑减速。节点入场、连线断裂用它。
pub fn ease_out_quad(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    1.0 - (1.0 - t) * (1.0 - t)
}

/// 三次方缓出：收得更快、尾巴更平。刀光收回用它。
pub fn ease_out_cubic(t: f32) -> f32 {
    let t = t.clamp(0.0, 1.0);
    1.0 - (1.0 - t).powi(3)
}

/// 「待命 / 活性」呼吸的频率（弧度/秒）。
///
/// 端点搏动、待连的线、刀光扫到的线、运行药丸的闪动 —— 凡是「在等你 / 在跑」的搏动
/// 一律用它，各处节奏才一致。
pub const BREATH: f64 = 5.0;
